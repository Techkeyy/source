"""Offline grounded-matching check over the real Phase 2 artifacts.

The inputs are the real website extraction and provider records generated by
the other feasibility scripts. The decision rule is deterministic and
conservative. The proposal draft is intentionally plain and uses only claims
found in the extracted profile.
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path


ROOT = Path(__file__).parent
WEBSITE_PATH = ROOT / "website-analysis-results-2026-10-14.json"
DISCOVERY_PATH = ROOT / "discovery-analysis-results-2026-10-14.json"


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def evidence_for_terms(profile: dict, terms: list[str]) -> list[dict]:
    matched = []
    for item in profile.get("evidence", []):
        text = f"{item.get('value', '')} {item.get('excerpt', '')}".lower()
        if any(term.lower() in text for term in terms):
            matched.append(item)
    return matched


def matches_profile(record: dict, profile_terms: list[str]) -> list[str]:
    text = f"{record.get('title', '')} {record.get('description_excerpt', '')}".lower()
    return [term for term in profile_terms if re.search(r"\b" + re.escape(term) + r"\b", text)]


def decide(record: dict, cutoff: datetime, profile_terms: list[str]) -> dict:
    published = record.get("published_at")
    when = datetime.fromisoformat(published) if published else None
    fresh = bool(when and when >= cutoff)
    overlap = matches_profile(record, profile_terms)
    reasons = []
    if not record.get("canonical_url"):
        reasons.append("no canonical source URL was returned")
    if not fresh:
        reasons.append("record is outside the 30-day feasibility freshness window")
    if record.get("classification") == "permanent_or_unspecified_employment":
        reasons.append("record is permanent or employment-type is not freelance/contract")
    if record.get("classification") == "irrelevant_or_unclear":
        reasons.append("record does not contain a clear opportunity or demand signal")
    if not overlap:
        reasons.append("no overlap with the confirmed profile vocabulary")
    accepted = (
        fresh
        and bool(record.get("canonical_url"))
        and bool(overlap)
        and record.get("classification")
        in {"explicit_freelance_or_contract", "potential_buyer_signal_unconfirmed"}
    )
    return {
        "decision": "ACCEPT_FOR_REVIEW" if accepted else "REJECT",
        "title": record.get("title"),
        "source": record.get("source"),
        "canonical_url": record.get("canonical_url"),
        "published_at": published,
        "classification": record.get("classification"),
        "profile_overlap": overlap,
        "reasons": ["fresh, source-linked, non-permanent signal with profile overlap"]
        if accepted
        else reasons,
        "source_excerpt": record.get("description_excerpt", "")[:500],
    }


def proposal_draft(accepted: dict, profile: dict, profile_url: str) -> str:
    supported = [
        item["value"]
        for item in profile.get("evidence", [])
        if item.get("field") in {"what_it_does", "service_or_product_signal", "technology_signal"}
    ]
    supported = supported[:3]
    claim_text = "; ".join(supported)
    return (
        f"Hello,\\n\\nI found your public opportunity, “{accepted['title']},” on "
        f"{accepted['source']}. The source describes this as: "
        f"“{accepted['source_excerpt'][:220]}”.\\n\\n"
        f"My public profile describes my work as: {claim_text}. "
        f"I would be glad to discuss whether that background fits this request. "
        f"You can review the supporting profile evidence here: {profile_url}.\\n\\n"
        "If useful, I can share a short plan and clarify scope, timing, and "
        "requirements before proposing any commercial terms.\\n\\nRegards"
    )


def main() -> int:
    website = load_json(WEBSITE_PATH)
    discovery = load_json(DISCOVERY_PATH)
    frog = next(item for item in website["sites"] if item["label"] == "agency-or-service")
    profile = frog["profile"]
    # These are normalized, reviewable terms grounded in the frog evidence.
    profile_terms = ["ai", "design", "research", "experience", "strategy"]
    profile_url = frog["fetch"]["final_url"]
    cutoff = datetime.fromisoformat(discovery["test_date_utc"]) - timedelta(days=30)
    records = []
    for provider in discovery["providers"]:
        records.extend(provider["sample_records"])
    decisions = [decide(record, cutoff, profile_terms) for record in records]
    accepted = next(
        (
            item
            for item in decisions
            if item["decision"] == "ACCEPT_FOR_REVIEW"
            and item["source"] in {"Remote OK", "Himalayas", "Jobicy"}
        ),
        None,
    )
    rejected = next(
        (
            item
            for item in decisions
            if item["decision"] == "REJECT"
            and "permanent or employment-type" in " ".join(item["reasons"])
        ),
        None,
    )
    output = {
        "test": "grounded-matching-feasibility",
        "test_date_utc": discovery["test_date_utc"],
        "profile": {
            "source_url": profile_url,
            "confirmed_terms_used": profile_terms,
            "supporting_evidence": evidence_for_terms(profile, profile_terms),
            "unsupported_claims_detected": profile.get("unsupported_claims_detected", []),
        },
        "accepted_example": accepted,
        "rejected_example": rejected,
        "proposal": (
            {
                "status": "DRAFTED_FROM_SUPPORTED_CLAIMS",
                "text": proposal_draft(accepted, profile, profile_url),
                "boundary": "Editable draft only; no auto-send and no unsupported past-client, ownership, pricing, or guarantee claims.",
            }
            if accepted
            else {
                "status": "BLOCKED",
                "reason": "No acceptable source-linked non-permanent candidate in the stored sample.",
            }
        ),
        "decision_rule": {
            "accept_only_if": [
                "fresh within the 30-day feasibility window",
                "canonical source URL exists",
                "classification is explicit freelance/contract or unconfirmed public demand",
                "at least one normalized profile term appears in source text",
            ],
            "reject_if": [
                "permanent/unspecified employment",
                "stale",
                "no source URL",
                "no profile overlap",
                "irrelevant or unclear signal",
            ],
        },
        "overall_status": "PASS" if accepted and rejected else "HOLD",
    }
    destination = ROOT / "matching-analysis-results-2026-10-14.json"
    destination.write_text(json.dumps(output, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(output, indent=2, ensure_ascii=False))
    print("Wrote:", destination)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
